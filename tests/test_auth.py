class CheckerTest(unittest.TestCase):
    def test_invalid_descriptions_are_rejected_with_their_line(self):
        for description, text, line in INVALID:
            with self.subTest(description):
                with self.assertRaises(IntentError) as caught:
                    pages.parse(text)
                self.assertEqual(caught.exception.line, line, caught.exception.message)

    def test_each_rule_says_what_is_wrong(self):
        expected = {
            "authentication without a database": "authentication needs a database and a web framework",
            "authentication with no sign-in page": "needs one page with a sign-in form",
            "two sign-in forms": "already a sign-in form",
            "a table on the sign-in page": "may hold only headings, text and the sign-in form",
            "only the sign-in page": "at least one page besides the sign-in page",
            "sign in without authentication": "needs 'use authentication'",
            "signing out without authentication": "needs 'use authentication'",
            "sign in with three texts": "four texts in double quotes",
            "data whose table is the users'": "where the users and their sessions are kept",
        }
        texts = {description: text for description, text, _ in INVALID}
        for description, message in expected.items():
            with self.subTest(description):
                with self.assertRaises(IntentError) as caught:
                    pages.parse(texts[description])
                self.assertIn(message, caught.exception.message)

    def test_use_authentication_is_built_not_merely_understood(self):
        for text in (EXAMPLE, pages.render(pages.parse(EXAMPLE), "es")):
            result = analyse(text)
            self.assertTrue(result["complete"], result["problems"])
            use = next(statement for statement in result["statements"] if statement["text"].endswith(("authentication", "autenticación")))
            self.assertEqual(use["status"], "standard")
            self.assertEqual([block["block"] for block in use["blocks"]], ["authentication"])



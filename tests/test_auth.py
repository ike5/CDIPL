def without_trace(files):
    return {name: text for name, text in files.items() if name != "trace.json"}


def write(folder, files):
    for name, text in files.items():
        path = Path(folder) / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def load_server(folder, name):
    spec = importlib.util.spec_from_file_location(name, Path(folder) / "server.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def command(folder, *arguments, stdin=""):
    """Run one of the generated server's commands, as a person would from the generated folder."""
    return subprocess.run([sys.executable, "server.py", *arguments], input=stdin, cwd=folder, capture_output=True,
                          text=True, check=False, timeout=60)


def raw_get(app, path, cookie=None):
    """Send a request whose path is passed to the server exactly as written, with no clean-up by a client."""
    messages, received = [], []
    headers = [(b"host", b"testserver")] + ([(b"cookie", f"session={cookie}".encode())] if cookie else [])

    async def receive():
        if received:  # the client stays connected until the response is complete
            await asyncio.Event().wait()
        received.append(True)
        return {"type": "http.request", "body": b"", "more_body": False}

    async def send(message):
        messages.append(message)

    scope = {"type": "http", "asgi": {"version": "3.0"}, "http_version": "1.1", "method": "GET", "scheme": "http",
             "path": path, "raw_path": path.encode(), "query_string": b"", "root_path": "", "headers": headers,
             "client": ("127.0.0.1", 1), "server": ("testserver", 80)}
    asyncio.run(app(scope, receive, send))
    return next(message["status"] for message in messages if message["type"] == "http.response.start")



    def test_the_lock_starts_after_five_failures_and_ends_after_five_minutes(self):
        start = 1_900_000_000
        client = self.client()

        def sign_in(password):
            return client.post("/api/sign-in", json={"name": "alice", "password": password}).status_code

        with mock.patch.object(self.server, "time", Clock(start)) as clock:
            for _ in range(4):
                self.assertEqual(sign_in("wrong password"), 401)
            self.assertEqual(sign_in(PASSWORD), 204)  # a success resets the count
            for _ in range(5):
                self.assertEqual(sign_in("wrong password"), 401)
            self.assertEqual(sign_in(PASSWORD), 401)  # locked: the right password is refused too
            clock.now = start + 5 * 60 - 1
            self.assertEqual(sign_in(PASSWORD), 401)
            with sqlite3.connect(self.database) as connection:  # attempts while locked are not counted
                self.assertEqual(connection.execute('SELECT failures, locked_until FROM "auth_user"').fetchone(), (5, start + 5 * 60))
            clock.now = start + 5 * 60
            self.assertEqual(sign_in(PASSWORD), 204)
            for _ in range(5):
                self.assertEqual(sign_in("wrong password"), 401)
            clock.now += 5 * 60
            self.assertEqual(sign_in("wrong password"), 401)  # after a lock, one more failure locks the name again
            self.assertEqual(sign_in(PASSWORD), 401)
            clock.now += 5 * 60
            self.assertEqual(sign_in(PASSWORD), 204)

    def test_attempts_made_at_the_same_moment_are_all_counted(self):
        checked, real = [], self.server.password_hash

        def counting(password, salt):
            if salt != self.server.DUMMY_SALT:
                checked.append(password)
            return real(password, salt)

        def attempt(_):
            return self.client().post("/api/sign-in", json={"name": "alice", "password": "wrong password"}).status_code

        with mock.patch.object(self.server, "password_hash", counting), ThreadPoolExecutor(10) as pool:
            replies = list(pool.map(attempt, range(20)))
        self.assertEqual(set(replies), {401})
        self.assertEqual(len(checked), 5)  # only five passwords were tried against the stored hash; the rest met the lock
        self.assertEqual(self.client().post("/api/sign-in", json={"name": "alice", "password": PASSWORD}).status_code, 401)

    def test_the_database_holds_neither_the_password_nor_the_token(self):
        client = self.signed_in()
        token = client.cookies["session"]
        stored = self.database.read_bytes()
        for secret in (PASSWORD, token):
            self.assertNotIn(secret.encode("utf-8"), stored)
        with sqlite3.connect(self.database) as connection:
            self.assertEqual(connection.execute('SELECT token_hash FROM "auth_session"').fetchone(),
                             (hashlib.sha256(token.encode("utf-8")).hexdigest(),))
            salt, digest = connection.execute('SELECT salt, hash FROM "auth_user"').fetchone()
        self.assertEqual((len(salt), len(digest)), (16, 32))
        self.assertEqual(digest, hashlib.scrypt(PASSWORD.encode("utf-8"), salt=salt, n=2**14, r=8, p=1, dklen=32))

    def test_what_is_sent_to_sign_in_is_checked_before_it_is_hashed(self):
        client = self.client()
